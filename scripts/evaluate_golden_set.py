"""Run a Golden Set against saved predictions or the V2 SSE endpoint.

Examples (Windows CMD):
  python scripts/evaluate_golden_set.py --predictions evals/sample_predictions.jsonl
  python scripts/evaluate_golden_set.py --base-url http://localhost:8000 --enforce-gates
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
import hashlib
import json
import os
from pathlib import Path
import sys
import time
from typing import Any
import uuid

import requests

# Running ``python scripts\\evaluate_golden_set.py`` makes Python place only
# ``scripts/`` on sys.path.  Insert the repository root so the command works
# exactly as documented for Windows CMD users.
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.app.evaluation.golden_set import (
    GoldenCase,
    compare_to_baseline,
    evaluate_quality_gates,
    load_golden_set,
    summarise_results,
)

DEFAULT_GOLDEN_SET = ROOT / "evals" / "golden_set_zh_v2.jsonl"
DEFAULT_THRESHOLDS = ROOT / "evals" / "quality_thresholds.json"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate the Triple-U V2 Agent/RAG Golden Set")
    parser.add_argument("--golden-set", type=Path, default=DEFAULT_GOLDEN_SET)
    parser.add_argument("--predictions", type=Path, help="JSONL predictions generated by a prior run")
    parser.add_argument("--base-url", help="V2 backend URL, for example http://localhost:8000")
    parser.add_argument("--token", help="Bearer token for V2_AUTH_REQUIRED deployments")
    parser.add_argument("--login-account", help="Demo account used to obtain a token without printing it")
    parser.add_argument("--login-password", help="Password for --login-account")
    parser.add_argument("--login-from-env", action="store_true",
                        help="Read V2_EVAL_LOGIN_ACCOUNT/PASSWORD from environment")
    parser.add_argument("--output", type=Path, default=ROOT / "reports" / "golden_set_v2_report.json")
    parser.add_argument("--progress", type=Path,
                        help="Append and fsync each online prediction to this new JSONL file")
    parser.add_argument("--resume", action="store_true",
                        help="Resume a prior --progress file without rerunning saved cases")
    parser.add_argument("--overwrite", action="store_true", help="Explicitly replace an existing output report")
    parser.add_argument("--baseline", type=Path, help="Prior Golden Set JSON report for regression comparison")
    parser.add_argument("--timeout", type=int, default=90, help="Per SSE request timeout in seconds")
    parser.add_argument(
        "--retries",
        type=int,
        default=1,
        help="Retry transient SSE connection/time-out failures this many times (default: 1)",
    )
    parser.add_argument(
        "--case-id",
        action="append",
        default=[],
        help="Run only one or more case IDs; useful for a low-cost online smoke check",
    )
    parser.add_argument("--enforce-gates", action="store_true", help="Return code 1 when a target gate fails")
    return parser.parse_args()


def load_predictions(path: Path) -> dict[str, dict[str, Any]]:
    predictions: dict[str, dict[str, Any]] = {}
    for line_number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not raw_line.strip():
            continue
        raw = json.loads(raw_line)
        case_id = str(raw.get("id", ""))
        if not case_id:
            raise ValueError(f"Prediction line {line_number} has no id")
        predictions[case_id] = raw
    return predictions


def run_live_case(
    base_url: str,
    case: GoldenCase,
    timeout: int,
    token: str = "",
    retries: int = 1,
) -> dict[str, Any]:
    """Execute one V2 SSE request and translate it into a provider-neutral prediction."""
    url = f"{base_url.rstrip('/')}/api/v2/learning-runs/stream"
    started = time.perf_counter()
    final: dict[str, Any] = {}
    attempts = max(0, int(retries)) + 1
    for attempt in range(attempts):
        final = {}
        terminal_seen = False
        # A unique thread prevents an interrupted human-review Golden case from
        # leaking checkpoint state into a retry or later evaluation run.
        payload = {
            "message": case.question,
            "course_id": case.course_id,
            "session_id": f"golden-{case.case_id}-{uuid.uuid4().hex[:8]}",
            "user_id": "anonymous",
            "require_approval": case.require_approval,
        }
        events: list[str] = []
        event_name = ""
        try:
            headers = {"Authorization": f"Bearer {token}"} if token else None
            with requests.post(url, json=payload, headers=headers, stream=True, timeout=timeout) as response:
                response.raise_for_status()
                for line in response.iter_lines(decode_unicode=True):
                    if line.startswith("event: "):
                        event_name = line.removeprefix("event: ").strip()
                        events.append(event_name)
                    elif line.startswith("data: "):
                        try:
                            data = json.loads(line.removeprefix("data: "))
                        except json.JSONDecodeError:
                            continue
                        if event_name == "run.completed":
                            final = data if isinstance(data, dict) else {}
                            terminal_seen = True
                        elif event_name == "run.failed":
                            final = {"error": data.get("error", "run_failed")} if isinstance(data, dict) else {}
                            terminal_seen = True
                        elif event_name == "review.required":
                            final = data if isinstance(data, dict) else {}
                            terminal_seen = True
                            approval = final.get("approval", {})
                            if isinstance(approval, dict):
                                # Preserve leaked drafts/sources so the evaluator
                                # can fail the case instead of discarding evidence.
                                final["answer"] = approval.get("draft_answer", "")
                                final["citations"] = approval.get("citations", [])
                                final["evidence"] = approval.get("evidence", [])
            if not terminal_seen:
                final["error"] = "stream_ended_without_terminal_event"
            final["events"] = events
            break
        except requests.RequestException as exc:
            final = {"error": str(exc), "events": events}
            retryable = isinstance(exc, (requests.Timeout, requests.ConnectionError))
            if not retryable or attempt + 1 >= attempts:
                break
            time.sleep(min(2**attempt, 4))
    final["attempts"] = attempt + 1
    final["latency_ms"] = round((time.perf_counter() - started) * 1000, 2)
    return final


def run_live(
    base_url: str, cases: list[GoldenCase], timeout: int, token: str = "", retries: int = 1,
    progress: Path | None = None, resume: bool = False,
) -> dict[str, dict[str, Any]]:
    def fingerprint(case: GoldenCase) -> str:
        payload = json.dumps(asdict(case), sort_keys=True, ensure_ascii=False)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    saved: dict[str, dict[str, Any]] = {}
    if resume:
        if progress is None or not progress.is_file():
            raise ValueError("resume_progress_required")
        for raw in progress.read_text(encoding="utf-8").splitlines():
            item = json.loads(raw)
            saved[item["id"]] = item
        expected = {case.case_id: fingerprint(case) for case in cases}
        if any(case_id not in expected or item.get("case_sha256") != expected[case_id]
               for case_id, item in saved.items()):
            raise ValueError("progress_case_mismatch")
    if progress is not None:
        progress.parent.mkdir(parents=True, exist_ok=True)
        stream = progress.open("a" if resume else "x", encoding="utf-8")
    else:
        stream = None
    try:
        predictions = {case_id: item["prediction"] for case_id, item in saved.items()}
        for case in cases:
            if case.case_id in predictions:
                continue
            prediction = run_live_case(base_url, case, timeout, token, retries)
            if stream is not None:
                stream.write(json.dumps({"id": case.case_id,
                                         "case_sha256": fingerprint(case),
                                         "prediction": prediction}, ensure_ascii=False) + "\n")
                stream.flush()
                os.fsync(stream.fileno())
            predictions[case.case_id] = prediction
        return predictions
    finally:
        if stream is not None:
            stream.close()


def login_for_token(base_url: str, account: str, password: str, timeout: int) -> str:
    response = requests.post(
        f"{base_url.rstrip('/')}/api/v1/auth/login",
        json={"account": account, "password": password},
        timeout=timeout,
    )
    response.raise_for_status()
    token = str(response.json().get("access_token", ""))
    if not token:
        raise RuntimeError("login_response_missing_access_token")
    return token


def main() -> int:
    args = parse_args()
    if args.output.exists() and not args.overwrite:
        raise SystemExit("Output already exists; choose a new --output or explicitly use --overwrite")
    if bool(args.predictions) == bool(args.base_url):
        raise SystemExit("Specify exactly one of --predictions or --base-url")
    if args.resume and not args.progress:
        raise SystemExit("--resume requires --progress")
    if args.progress and not args.base_url:
        raise SystemExit("--progress requires --base-url")
    if bool(args.login_account) != bool(args.login_password):
        raise SystemExit("Specify --login-account and --login-password together")
    if args.login_from_env and (args.login_account or args.login_password or args.token):
        raise SystemExit("Choose only one login source")
    cases = load_golden_set(args.golden_set)
    if args.case_id:
        requested = set(args.case_id)
        cases = [case for case in cases if case.case_id in requested]
        missing = requested - {case.case_id for case in cases}
        if missing:
            raise SystemExit(f"Golden Set case ID not found: {', '.join(sorted(missing))}")
    token = args.token or ""
    if args.login_from_env:
        account = os.getenv("V2_EVAL_LOGIN_ACCOUNT", "")
        password = os.getenv("V2_EVAL_LOGIN_PASSWORD", "")
        if not account or not password:
            raise SystemExit("evaluation_login_environment_required")
        args.login_account, args.login_password = account, password
    if args.base_url and args.login_account:
        token = login_for_token(args.base_url, args.login_account, args.login_password, args.timeout)
    predictions = (
        load_predictions(args.predictions)
        if args.predictions
        else run_live(args.base_url, cases, args.timeout, token, args.retries,
                      args.progress, args.resume)
    )
    report = summarise_results(cases, predictions)
    thresholds = json.loads(DEFAULT_THRESHOLDS.read_text(encoding="utf-8"))
    gates = evaluate_quality_gates(report, thresholds)
    if args.baseline:
        baseline = json.loads(args.baseline.read_text(encoding="utf-8"))
        regression = compare_to_baseline(
            report,
            baseline,
            tolerated_drop=float(thresholds.get("max_relative_regression", 0.03)),
        )
        report["baseline_comparison"] = regression
        gates["baseline_regression"] = bool(regression["passed"])
    report["quality_gates"] = gates
    report["thresholds"] = thresholds
    report["evaluation_mode"] = "offline_predictions" if args.predictions else "online"
    report["predictions"] = predictions
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"summary": report["summary"], "quality_gates": gates, "report": str(args.output)}, ensure_ascii=False, indent=2))
    return 0 if not args.enforce_gates or all(gates.values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())
