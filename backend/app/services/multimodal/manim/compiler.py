"""
DSL Compiler — 将 ManimDSLSpec 编译为安全的 Manim Python 代码

核心安全保证:
    - 不拼接用户字符串到 Python 代码中（所有内容变量在运行时通过 safe_globals 注入）
    - 只生成白名单内的 Manim API 调用
    - 生成的代码是确定性模板 + 参数填充，不是 LLM 自由输出

生成的代码示例:
    ```python
    from manim import *
    class Scene_1(Scene):
        def construct(self):
            title = Text(DATA["title"], font_size=48, color=WHITE)
            title.to_corner(UP)
            self.play(Write(title))
            ...
    ```

Phase 2 计划: 用 Jinja2 模板引擎替代字符串拼接，支持更复杂的场景编排。
"""
from __future__ import annotations

import ast
import re
import textwrap
from typing import Any, Dict, List, Optional, Tuple

from backend.app.services.multimodal.manim.dsl import (
    AnimationStep,
    AnimationType,
    Color,
    ElementType,
    ManimDSLSpec,
    Position,
    Scene,
    SceneElement,
)

# ================================================================
# 位置映射表
# ================================================================
POSITION_MAP: Dict[Position, str] = {
    Position.TOP: "UP * 3",
    Position.BOTTOM: "DOWN * 3",
    Position.LEFT: "LEFT * 5",
    Position.RIGHT: "RIGHT * 5",
    Position.CENTER: "ORIGIN",
    Position.TOP_LEFT: "UP * 3 + LEFT * 5",
    Position.TOP_RIGHT: "UP * 3 + RIGHT * 5",
    Position.BOTTOM_LEFT: "DOWN * 3 + LEFT * 5",
    Position.BOTTOM_RIGHT: "DOWN * 3 + RIGHT * 5",
    Position.UP: "UP * 2",
    Position.DOWN: "DOWN * 2",
}

# 6 种元素 → Manim Mobject 构造映射
ELEMENT_CONSTRUCTORS: Dict[ElementType, str] = {
    ElementType.TEXT: "Text",
    ElementType.FORMULA: "MathTex",
    ElementType.CODE: "Code",
    ElementType.SHAPE: "Rectangle",
    ElementType.AXES: "Axes",
    ElementType.BULLET_LIST: "BulletedList",
}

# 动画映射
ANIMATION_MAP: Dict[AnimationType, str] = {
    AnimationType.WRITE: "Write",
    AnimationType.FADE_IN: "FadeIn",
    AnimationType.FADE_OUT: "FadeOut",
    AnimationType.TRANSFORM: "Transform",
    AnimationType.MOVE_TO: "move_to",
    AnimationType.SCALE: "scale",
    AnimationType.ROTATE: "Rotate",
    AnimationType.HIGHLIGHT: "Indicate",
    AnimationType.CREATE: "Create",
    AnimationType.INDICATE: "Indicate",
}


# ================================================================
# DSL Compiler
# ================================================================
class DSLCompiler:
    """将 ManimDSLSpec 编译为可运行的 Manim Python 脚本"""

    # 最大生成的 Python 文件行数 (安全上限)
    MAX_LINES: int = 500

    def compile(self, spec: ManimDSLSpec) -> str:
        """编译 DSL → Manim Python

        Args:
            spec: 已验证的 ManimDSLSpec

        Returns:
            完整的 Manim Python 脚本字符串

        Raises:
            ValueError: DSL 不合法
        """
        self._validate_spec(spec)

        lines: List[str] = []
        lines.extend(self._gen_header(spec))
        lines.append("")
        lines.extend(self._gen_data_block(spec))
        lines.append("")

        for scene in spec.scenes:
            lines.extend(self._gen_scene_class(scene, spec))
            lines.append("")

        lines.extend(self._gen_main_block(spec))

        code = "\n".join(lines)
        if len(code.split("\n")) > self.MAX_LINES:
            raise ValueError(
                f"Generated code too long ({len(code.splitlines())} lines > {self.MAX_LINES})"
            )
        return code

    def _validate_spec(self, spec: ManimDSLSpec) -> None:
        """额外验证 (Pydantic 已做基础验证)

        允许 element_count == 0 (e.g. 纯占位场景), 但仍校验 id 唯一性。
        """
        seen_ids: set = set()
        for scene in spec.scenes:
            for elem in scene.elements:
                if elem.id in seen_ids:
                    raise ValueError(f"Duplicate element id: {elem.id}")
                seen_ids.add(elem.id)

    # ----------------------------------------------------------------
    # 代码生成: Header
    # ----------------------------------------------------------------
    def _gen_header(self, spec: ManimDSLSpec) -> List[str]:
        return [
            "# Auto-generated by ManimDSLCompiler v1",
            f"# Topic: {spec.topic}",
            f"# Scenes: {len(spec.scenes)}  Elements: {spec.element_count()}",
            "# DO NOT EDIT — regenerated from DSL on each run",
            "",
            "from manim import *",
            "import json",
            "",
            f"# Global animation speed factor",
            f"ANIM_SPEED = {spec.animation_speed}",
            f"BG_COLOR = '{spec.scenes[0].background_color if spec.scenes else '#1A1A2E'}'",
        ]

    # ----------------------------------------------------------------
    # 代码生成: Data Block
    # ----------------------------------------------------------------
    def _gen_data_block(self, spec: ManimDSLSpec) -> List[str]:
        """生成 DATA 字典 — 所有用户内容注入点

        安全保证 (参数化):
        - Manim 类只通过 DATA["key"] 引用内容, 不做字符串拼接
        - 内容存在 DATA dict 中, 不会变成可执行的代码标识符
        - 阻止内容侧的代码注入 (即便 content 含特殊字符)
        """
        import json

        data: Dict[str, Any] = {
            "title": spec.title,
            "description": spec.description,
            "topic": spec.topic,
        }
        for scene in spec.scenes:
            for elem in scene.elements:
                key = f"{scene.scene_id}_{elem.id}"
                data[key] = elem.content

        return [
            "# ---- Runtime Data (parameterized via DATA dict) ----",
            f"DATA = {json.dumps(data, ensure_ascii=False)}",
            "# ----------------------------------------------------",
        ]

    # ----------------------------------------------------------------
    # 代码生成: Scene Class
    # ----------------------------------------------------------------
    def _gen_scene_class(self, scene: Scene, spec: ManimDSLSpec) -> List[str]:
        class_name = self._to_class_name(scene.scene_id)
        lines: List[str] = [
            f"class {class_name}(Scene):",
            f'    """{scene.title or scene.scene_id}"""',
            "",
            "    def construct(self):",
            f"        self.camera.background_color = BG_COLOR",
        ]

        if scene.elements:
            lines.append("")
            lines.append("        # ---- Elements ----")
            for elem in scene.elements:
                lines.extend(self._gen_element_creation(elem, scene.scene_id))

        if scene.animations:
            lines.append("")
            lines.append("        # ---- Animations ----")
            for anim in scene.animations:
                lines.extend(self._gen_animation(anim))

            lines.append("")
            # 最后一帧保持
            lines.append(f"        self.wait({max(0.5, scene.duration_seconds * 0.15):.1f})")
        else:
            lines.append(f"        self.wait({scene.duration_seconds:.1f})")

        return lines

    def _gen_element_creation(self, elem: SceneElement, scene_id: str) -> List[str]:
        """生成单个元素的 Manim 构造代码"""
        var = self._to_var_name(elem.id)
        constr = ELEMENT_CONSTRUCTORS.get(elem.type, "Text")
        data_key = f"{scene_id}_{elem.id}"

        lines: List[str] = []

        # 特殊元素
        if elem.type == ElementType.FORMULA:
            lines.append(
                f"        {var} = {constr}(DATA['{data_key}'], "
                f"font_size={elem.style.font_size}, "
                f"color='{elem.style.color}')"
            )
        elif elem.type == ElementType.CODE:
            lines.append(
                f"        {var} = {constr}("
                f"code=DATA['{data_key}'], "
                f"language='python', "
                f"font_size={max(16, elem.style.font_size - 12)}, "
                f"line_spacing=0.6, "
                f"background='window'"
                f")"
            )
        elif elem.type == ElementType.SHAPE:
            lines.append(
                f"        {var} = {constr}("
                f"width={elem.width}, height={elem.height}, "
                f"color='{elem.style.color}', "
                f"fill_opacity={elem.style.fill_opacity})"
            )
        elif elem.type == ElementType.BULLET_LIST:
            items = [i.strip() for i in elem.content.split("\n") if i.strip()]
            if items:
                items_str = ", ".join(f'"{i}"' for i in items[:8])
                lines.append(
                    f"        {var} = BulletedList({items_str}, "
                    f"font_size={elem.style.font_size})"
                )
            else:
                lines.append(f"        {var} = Text('•', font_size={elem.style.font_size})")
        elif elem.type == ElementType.AXES:
            # 生成坐标轴 (x_range, y_range from metadata)
            x_range = elem.metadata.get("x_range", [-5, 5, 1])
            y_range = elem.metadata.get("y_range", [-3, 3, 1])
            lines.append(
                f"        {var} = Axes("
                f"x_range={x_range}, y_range={y_range}, "
                f"axis_config={{'color': '{elem.style.color}'}}"
                f")"
            )
        else:
            # TEXT / GRAPH / IMAGE — default Text rendering
            lines.append(
                f"        {var} = {constr}(DATA['{data_key}'], "
                f"font_size={elem.style.font_size}, "
                f"color='{elem.style.color}')"
            )

        # 位置
        pos = POSITION_MAP.get(elem.position, "ORIGIN")
        if elem.shift_x != 0.0 or elem.shift_y != 0.0:
            lines.append(
                f"        {var}.move_to({pos} + RIGHT * {elem.shift_x:.1f} + UP * {elem.shift_y:.1f})"
            )
        else:
            lines.append(f"        {var}.move_to({pos})")

        return lines

    def _gen_animation(self, anim: AnimationStep) -> List[str]:
        """生成单步动画代码"""
        anim_func = ANIMATION_MAP.get(anim.type, "Write")
        target = self._to_var_name(anim.target_id) if anim.target_id else "None"
        run_time = f"{anim.duration:.1f} * ANIM_SPEED"

        if anim.type == AnimationType.MOVE_TO:
            direction = anim.params.get("direction", "RIGHT")
            amount = anim.params.get("amount", 1.0)
            return [
                f"        self.play("
                f"{target}.animate.shift({direction} * {amount}), "
                f"run_time={run_time})"
            ]
        elif anim.type == AnimationType.SCALE:
            factor = anim.params.get("factor", 1.5)
            return [
                f"        self.play("
                f"{target}.animate.scale({factor}), "
                f"run_time={run_time})"
            ]
        elif anim.type == AnimationType.TRANSFORM:
            from_id = anim.params.get("from_id", "")
            from_var = self._to_var_name(from_id) if from_id else "None"
            return [f"        self.play(Transform({from_var}, {target}), run_time={run_time})"]
        else:
            return [f"        self.play({anim_func}({target}), run_time={run_time})"]

    # ----------------------------------------------------------------
    # 代码生成: Main Block
    # ----------------------------------------------------------------
    def _gen_main_block(self, spec: ManimDSLSpec) -> List[str]:
        lines = [
            "# ---- Render Entry Point ----",
            "if __name__ == '__main__':",
        ]
        for scene in spec.scenes:
            class_name = self._to_class_name(scene.scene_id)
            lines.append(f"    {class_name}().render()")
        return lines

    # ----------------------------------------------------------------
    # 命名工具
    # ----------------------------------------------------------------
    @staticmethod
    def _to_class_name(scene_id: str) -> str:
        """scene_id → SceneClassName"""
        safe = re.sub(r'[^a-zA-Z0-9_]', '_', scene_id)
        return f"Scene_{safe}" if not safe[0].isupper() else safe

    @staticmethod
    def _to_var_name(elem_id: str) -> str:
        """element.id → Python 变量名"""
        safe = re.sub(r'[^a-zA-Z0-9_]', '_', elem_id)
        return safe if safe[0].isalpha() else f"el_{safe}"


# ================================================================
# 安全校验器
# ================================================================
class ManimSafetyValidator:
    """对编译后的 Manim Python 代码做 AST 终检

    检查项:
    - 无危险导入 (os/sys/subprocess/socket/...)
    - 无 exec/eval/compile/__import__
    - 无文件 I/O (open)
    - 无网络调用
    """

    BLOCKED_MODULES: Tuple[str, ...] = (
        "os", "sys", "subprocess", "shutil", "socket", "requests",
        "urllib", "http", "ftplib", "telnetlib", "pickle",
    )
    BLOCKED_FUNCTIONS: Tuple[str, ...] = (
        "exec", "eval", "compile", "__import__", "open",
        "input", "breakpoint",
    )

    def validate(self, code: str) -> Tuple[bool, str]:
        """验证代码安全性

        Returns:
            (safe, error_message)
        """
        try:
            tree = ast.parse(code)
        except SyntaxError as exc:
            return False, f"语法错误: {exc.msg}"

        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root = alias.name.split(".")[0]
                    if root in self.BLOCKED_MODULES:
                        return False, f"禁止导入: {alias.name}"
                    if root not in ("manim", "json", "math", "random", "typing", "collections", "itertools", "functools"):
                        pass  # 允许常见安全库

            if isinstance(node, ast.ImportFrom):
                if node.module and node.module.split(".")[0] in self.BLOCKED_MODULES:
                    return False, f"禁止导入: from {node.module}"

            if isinstance(node, ast.Call):
                if isinstance(node.func, ast.Name):
                    if node.func.id in self.BLOCKED_FUNCTIONS:
                        return False, f"禁止函数调用: {node.func.id}()"

        # 附加检查: 文件大小
        if len(code) > 50000:
            return False, "生成的代码过大"

        return True, ""


# ================================================================
# 错误模型
# ================================================================
class CompilationError(Exception):
    """DSL 编译错误"""
    pass


class SafetyError(Exception):
    """安全检查失败"""
    pass
